# Now I am ready to create the map
def create_map(df, pollutant):
  df = df.copy()
  #Ensuring the coordinates are in the correct form and dropping any NaN vals
  df["latitude"] = pd.to_numeric(df["latitude"], errors = "coerce")
  df["longitude"] = pd.to_numeric(df["longitude"], errors = "coerce")
  df = df.dropna(subset = ["latitude", "longitude"])

  df["colour_code"] = df[pollutant].apply(lambda x: colour_code(x, pollutant))

  # Creating the colours on the map
  colour_landmark = {"green":"green", "yellow":"gold", "red":"red", "Unknown":"lightgray"}

  fig = px.scatter_mapbox(
      df,
      lat = "latitude",
      lon = "longitude",
      color = "colour_code",
      color_discrete_map = colour_landmark,
      hover_name = "school_name",
      # This is to call all the data I want to show when the mouse hovers/click over a landmark.
      custom_data = [
          "school_name",
          "borough",
          "school_type",
          "device_id",
          "source",
          "PM25",
          "PM10",
          "NO2"
          "colour_code"
      ],
      zoom = 10,
      height = 675
  )

  fig.update_traces(
      marker = {"size":11},
      hovertemplate = (
          "<b>%{customdata[0]}</b><br>"
          "Borough: %{customdata[1]}<br>"
          "School Type: %{customdata[2]}<br>"
          "Device ID: %{customdata[3]}<br>"
          "Source: %{customdata[4]}<br>"
          "PM2.5: %{customdata[5]}<br>"
          "PM10: %{customdata[6]}<br>"
          "NO2: %{customdata[7]}<br>"
          "Status: %{customdata[8]}<extra></extra>"
      )
  )

  fig.update_layout(
      mapbox_style = "open-street-map",
      # This removes white spaces around the map
      margin = dict(l = 0, r = 0, t = 0, b = 0),
      legend_title = "Air Quality for {pollutant} alert band"
  )
  return fig

