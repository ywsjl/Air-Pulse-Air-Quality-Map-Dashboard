unified_sql_query = """
WITH latest_readings AS (
  SELECT
    r.device_id,
    r.species,
    r.value,
    r.time,
    ROW_NUMBER() OVER (
      PARTITION BY r.device_id, r.species
      ORDER BY r.time DESC
    ) AS rn
  FROM readings r
),
-- keeping only the latest reading because Render can't support historical data (too big)
latest_only AS(
    SELECT
      device_id,
      species,
      value,
      time
    FROM latest_readings
    -- because the readings are ranked from latest (desc order)
    -- 1 is calling the top reading for each device/species
    WHERE rn = 1
)
SELECT
  d.device_id,
  d.source,
  d.device_name,
  d.school_id,
  s.school_name,
  s.school_type,
  s.postcode,
  s.borough,
  s.centroid_lat AS latitude,
  s.centroid_lon AS longitude,
-- MAX ignores null values as CASE WHEN filters by species (value or null) per device
  MAX(CASE WHEN lo.species = 'PM25' THEN lo.value END) AS "PM2.5",
  MAX(CASE WHEN lo.species ='PM10' THEN lo.value END) AS "PM10",
  MAX(CASE WHEN lo.species = 'NO2' THEN lo.value END) AS "NO2",

  MAX(CASE WHEN lo.species = 'PM25' THEN lo.time END) AS "PM2.5_time",
  MAX(CASE WHEN lo.species ='PM10' THEN lo.time END) AS "PM10_time",
  MAX(CASE WHEN lo.species = 'NO2' THEN lo.time END) AS "NO2_time"

FROM devices d
JOIN schools s
  ON d.school_id = s.school_id
LEFT JOIN latest_only lo
  ON d.device_id = lo.device_id
-- use GROUP BY to get one row per device
GROUP BY
  d.device_id,
  d.source,
  d.device_name,
  d.school_id,
  s.school_name,
  s.school_type,
  s.postcode,
  s.borough,
  s.centroid_lat,
  s.centroid_lon

ORDER BY
  d.source,
  s.school_name,
  d.device_id;
"""

df_unified = pd.read_sql(unified_sql_query, engine)
print(df_unified)

"""#**Creating the Dashboard Analytics**
The dashboard will display Key Performace Indicators (KPI) such as number of active sensors, number of red alerts, and average pollutant levels.

In addition, the dashboard will include filters for borough, source, and school type filtering. There will also be a ranking chart to display the current five schools with high and low pollutants.

#**Creating the KPI calculation function**
"""

def build_KPIs(df):
  df = df.copy()

  # This section of code is for the number of active sensors
  # An active sensor is counted as long as it has 1 pollutant reading available
  active_pollutants = (
      df["PM2.5"].notna() |
      df["PM10"].notna() |
      df["NO2"].notna()
  )
  active_sensors = df.loc[active_pollutants, "device_id"].nunique()

  # This is for the number of red alerts per pollutant
  red_pm25 = df["PM25"].apply(lambda x: colour_code(x, "PM25")).eq("red").sum()
  red_pm10 = df["PM10"].apply(lambda x: colour_code(x, "PM10")).eq("red").sum()
  red_no2 = df["NO2"].apply(lambda x: colour_code(x, "NO2")).eq("red").sum()

  # This is for average pollutant levels per borough
  avg_pm25 = df["PM25"].mean()
  avg_pm10 = df["PM10"].mean()
  avg_no2 = df["NO2"].mean()

  borough_summary = (
      df.groupby("borough", dropna = False)[["PM25", "PM10", "NO2"]]
      .mean().reset_index().sort_values("borough")
  )
  return{
      "active_sensors": active_sensors,
      "red_pm25": int(red_pm25),
      "red_pm10": int(red_pm10),
      "red_no2": int(red_no2),
      "avg_pm25": avg_pm25,
      "avg_pm10": avg_pm10,
      "avg_no2": avg_no2,
      "borough_summary": borough_summary
  }

"""#**Creating the Ranking Chart function**"""

def build_ranking_chart(df, pollutant, n = 5):
  if pollutant not in ["PM2.5", "PM10", "NO2"]:
    raise ValueError("Polluntant must be one of PM2.5, PM10, NO2")

  df_ranking =df.copy()
  # Removing rows that currently don't have a reading
  # To ensure the ranking is done effectively
  df_ranking = df_ranking.dropna(subset = [pollutant])
  if df_ranking.empty:
    return px.bar(title = "No data currently available.")

  # Aggregate to school level
  df_ranking = (df_ranking.groupby(
      ["school_id", "school_name", "borough"],
      dropna = False)
  [pollutant].mean().reset_index()
  )

  top_rank = df_ranking.nlargest(n, pollutant).copy()
  top_rank["group"] = "Highest"

  bottom_rank = df_ranking.nsmallest(n, pollutant).copy()
  bottom_rank["group"] = "Lowest"

  df_ranking = pd.concat([top_rank, bottom_rank], ignore_indes = True)

  fig = px.bar(
      df_ranking,
      x = pollutant,
      y = "school_name",
      color = "group",
      hover_data = ["borough"],
      orientation = "h",
      title = f"Current highest and lowest {n} schools by {pollutant}"
  )

  fig.update_layout(yaxis = {"categoryorder": "total ascending"})
  return fig

"""#**Creating the average pollutant level per Borough bar chart function**"""

def build_borough_bar_chart(df, pollutant):
  if pollutant not in ["PM2.5", "PM10", "NO2"]:
    raise ValueError("Polluntant must be one of PM2.5, PM10, NO2")

  df_plot = (
      df.groupby("borough", dropna = False)[pollutant]
      .mean().reset_index().dropna(subset = [pollutant])
      .sort_values(pollutant, ascending = False)
  )
  if df_plot.empty:
    return px.bar(title = "No data currently available.")
  fig = px.bar(
      df_plot,
      x = "borough",
      y = pollutant,
      title = f"Current average {pollutant} levels per borough."
  )

